"""Generates the viewer's copies of the Python pipeline's settings, so the two cannot drift.
Writes viewer/lib/generated/*.js. Re-run after changing config.yaml, icp/schema.py, icp/extract.py or icp/store.py.
A test fails if the generated files are out of date."""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from icp import extract, schema, store  # noqa: E402
from icp.config import load_config  # noqa: E402

OUT = Path(__file__).resolve().parent.parent / "viewer" / "lib" / "generated"


def render():
    cfg = load_config()
    files = {
        "config.js": cfg,
        "extraction-schema.js": schema.EXTRACTION_SCHEMA,
        "prompts.js": {"extractSystem": extract.SYSTEM},
        "columns.js": {"columns": store.COLUMNS, "jsonCols": store.JSON_COLS},
    }
    return {name: "// GENERATED by scripts/sync_viewer_config.py. Do not edit.\nexport default "
            + json.dumps(obj, indent=2, sort_keys=True) + ";\n" for name, obj in files.items()}


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in render().items():
        (OUT / name).write_text(text)
    print("wrote", ", ".join(render()))
